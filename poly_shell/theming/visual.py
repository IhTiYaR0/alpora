"""Mode-independent appearance controls; only validated numbers reach Lua."""
from ..core.state import ConfigError, read_object

DEFAULTS = {
    "windowRadius": 16, "barRadius": 20, "panelRadius": 20,
    "barOpacity": 75, "panelOpacity": 75, "launcherOpacity": 75,
    "activeOpacity": 100, "inactiveOpacity": 100,
    "blurEnabled": True, "blurSize": 3, "blurPasses": 1,
    "launcherRadius": 20, "widgetRadius": 16, "notificationRadius": 13,
    "widgetOpacity": 75, "notificationOpacity": 75,
    "panelPadding": 16, "launcherPadding": 18, "notificationPadding": 12,
    "barBorder": 1, "panelBorder": 1, "launcherBorder": 1,
    "widgetBorder": 1, "notificationBorder": 1,
    "barShadow": 20, "panelShadow": 20, "launcherShadow": 20,
    "widgetShadow": 0, "notificationShadow": 0,
    "panelOpenMs": 320, "panelCloseMs": 200,
    "launcherOpenMs": 320, "launcherCloseMs": 200,
    "widgetAnimations": True, "widgetFadeMs": 420,
    "barHeight": 40, "barMargin": 20, "barTop": 12,
    "barLeft": 20, "barRight": 20, "barBottom": 8,
    "windowGap": 5, "windowMargin": 12,
}
LIMITS = {
    "windowRadius": (0, 32), "barRadius": (0, 20), "panelRadius": (0, 32),
    "barOpacity": (40, 100), "panelOpacity": (50, 100), "launcherOpacity": (75, 100),
    "activeOpacity": (60, 100), "inactiveOpacity": (60, 100),
    "blurSize": (1, 8), "blurPasses": (1, 2),
    "launcherRadius": (0, 32), "widgetRadius": (0, 32), "notificationRadius": (0, 32),
    "widgetOpacity": (40, 100), "notificationOpacity": (20, 100),
    "panelPadding": (8, 24), "launcherPadding": (8, 24), "notificationPadding": (6, 24),
    "barHeight": (32, 80), "barMargin": (0, 64), "barTop": (0, 64),
    "widgetFadeMs": (0, 800),
    "barLeft": (0, 128), "barRight": (0, 128), "barBottom": (0, 128),
    "windowGap": (0, 64), "windowMargin": (0, 128),
}
LIMITS.update({prefix + "Border": (0, 3) for prefix in ("bar", "panel", "launcher", "widget", "notification")})
LIMITS.update({prefix + "Shadow": (0, 100) for prefix in ("bar", "panel", "launcher", "widget", "notification")})
LIMITS.update({prefix + phase + "Ms": (0, 800) for prefix in ("panel", "launcher") for phase in ("Open", "Close")})


def validate(value):
    if not isinstance(value, dict) or set(value) - set(DEFAULTS):
        raise ConfigError("Unknown appearance parameters")
    result = dict(DEFAULTS, **value)
    for key, (low, high) in LIMITS.items():
        if type(result[key]) is not int or not low <= result[key] <= high:
            raise ConfigError(f"{key}: integer from {low} to {high} required")
    for key in ("blurEnabled", "widgetAnimations"):
        if type(result[key]) is not bool:
            raise ConfigError(f"{key}: boolean required")
    return result


def visual_for(paths):
    path = paths.config / "visual.json"
    document = read_object(path) if path.exists() else {"schemaVersion": 1, "values": {}}
    if document.get("schemaVersion") != 1:
        raise ConfigError("Unsupported appearance schema version")
    value = validate(document.get("values"))
    # Existing user geometry remains authoritative until explicitly saved here.
    from ..core.state import settings_for
    bar = settings_for(paths)["bar"]
    for key, old_key in (("barHeight", "height"), ("barMargin", "margin"), ("barTop", "top")):
        if key not in document["values"]:
            value[key] = bar[old_key]
    if "launcherRadius" not in document["values"]:
        value["launcherRadius"] = value["panelRadius"]
    for key in ("barLeft", "barRight"):
        if key not in document["values"]:
            value[key] = value["barMargin"]
    return value


def lua_for(value):
    v = validate(value)
    enabled = "true" if v["blurEnabled"] else "false"
    return ("-- Generated by Poly Shell. Edit through Appearance settings.\n"
            f"hl.config({{ general = {{ gaps_in = {v['windowGap']}, gaps_out = {v['windowMargin']} }},\n"
            "render = { new_render_scheduling = true }, decoration = {\n"
            f"  rounding = {v['windowRadius']},\n"
            f"  active_opacity = {v['activeOpacity'] / 100:.2f},\n"
            f"  inactive_opacity = {v['inactiveOpacity'] / 100:.2f},\n"
            f"  blur = {{ enabled = {enabled}, size = {v['blurSize']}, passes = {v['blurPasses']} }},\n"
            "} })\n"
            '-- Keep frequently updated terminal text out of full-window alpha blur.\n'
            'hl.window_rule({ name = "poly-foot-performance", match = { class = "^foot$" }, no_blur = true, force_rgbx = true })\n'
            '-- Settings renders its own material; do not blur application content behind it.\n'
            'hl.window_rule({ name = "poly-settings-performance", match = { class = "^poly-shell-settings$" }, no_blur = true })\n'
            'do local c = os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config"); local f = c .. "/hypr/poly-shell-theme.lua"; local h = io.open(f, "r"); if h then h:close(); dofile(f) end end\n')
