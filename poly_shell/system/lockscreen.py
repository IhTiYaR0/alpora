"""Native Hyprlock appearance only; never handles credentials or changes PAM."""
from datetime import datetime
import os
import re
import tempfile

from ..core.state import ConfigError, ROOT, Paths, read_object


def lock_date(now=None, locale='ru'):
    now = now or datetime.now().astimezone()
    if locale == 'vi':
        days = ('Thứ Hai', 'Thứ Ba', 'Thứ Tư', 'Thứ Năm', 'Thứ Sáu', 'Thứ Bảy', 'Chủ Nhật')
        return f'{days[now.weekday()]} · {now.day} tháng {now.month}'
    if locale == 'en':
        days = ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')
        months = ('January', 'February', 'March', 'April', 'May', 'June',
                  'July', 'August', 'September', 'October', 'November', 'December')
        return f'{days[now.weekday()]} · {months[now.month - 1]} {now.day}'
    days = ('понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота', 'воскресенье')
    months = ('января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
              'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря')
    return f'{days[now.weekday()]} · {now.day} {months[now.month - 1]}'


def lock_style(snapshot):
    appearance = snapshot.get('appearance', {})
    palette = snapshot.get('appearance', {}).get('palette') or snapshot['profile']['palette']
    def color(name, alpha='ff'):
        value = palette[name]
        if not isinstance(value, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
            raise ConfigError('Invalid lockscreen palette')
        return f'rgba({value[1:]}{alpha})'
    font = snapshot['settings']['bar']['fontFamily']
    title = str(appearance.get('label', 'Alpine')).upper()
    # Hyprlang assignments must stay single-line, without variable expansion.
    for value in (font, title):
        if not value.strip() or any(char in value for char in '\n\r\0$#{}<>'):
            raise ConfigError('Invalid lockscreen typography')
    def asset(name, fallback):
        value = appearance.get(name, fallback)
        if not isinstance(value, str):
            raise ConfigError('Invalid lockscreen asset')
        path = (ROOT / 'assets' / value).resolve()
        allowed = path.is_relative_to((ROOT / 'assets').resolve()) or (name == 'wallpaper' and path.is_relative_to((Paths.current().config / 'wallpapers').resolve()))
        if not allowed or not path.is_file():
            raise ConfigError('Lockscreen asset must be an existing theme asset')
        if any(char in str(path) for char in '\n\r\0$#'):
            raise ConfigError('Invalid lockscreen asset path')
        return path
    image = asset('wallpaper', 'wallpapers/alpine-dawn.png')
    clock_frame = asset('lockClockFrame', 'lockscreen/alpine-clock.png')
    return '\n'.join([
        '# Generated by Poly Shell. No authentication settings belong here.',
        f'$lockBackground = {color("background")}',
        f'$lockGlass = {color("background", "d9")}',
        f'$lockInput = {color("surface", "d9")}',
        f'$lockEdge = {color("accent", "80")}',
        f'$lockAccent = {color("accent")}',
        f'$lockText = {color("text")}',
        f'$lockMuted = {color("muted")}',
        '$lockAmber = rgba(' + palette.get('secondary', '#c09d76')[1:] + 'ff)',
        f'$lockFont = {font}', f'$lockClockFont = {"Outfit SemiBold" if font in ("Inter", "Noto Sans") else f"{font} SemiBold"}',
        f'$lockClockFrame = {clock_frame}',
        f'$lockTitle = {title} · ' + ('SESSION LOCKED' if snapshot.get('settings', {}).get('locale') == 'en' else ('PHIÊN ĐÃ KHÓA' if snapshot.get('settings', {}).get('locale') == 'vi' else 'СЕАНС ЗАБЛОКИРОВАН')),
        f'$lockWallpaper = {image}',
        f'$lockDateCommand = "{ROOT / "bin/poly-shell"}" lock-date',
        f'$lockMediaCommand = "{ROOT / "bin/poly-shell"}" lock-media',
        '$lockMotion = ' + ('false' if snapshot['settings'].get('reducedMotion') else 'true'),
        '',
    ])


def sync_lockscreen(paths):
    text = lock_style(read_object(paths.session))
    destination = paths.state / 'hyprlock-theme.conf'
    if destination.exists() and destination.read_text() == text:
        return
    paths.state.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', dir=paths.state, delete=False) as stream:
            temporary = stream.name
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, destination)
    finally:
        if temporary and os.path.exists(temporary):
            os.unlink(temporary)
