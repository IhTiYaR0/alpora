"""Read-only OSD values and theme-generated Mako styling."""
import os
import re
import subprocess
import tempfile

from .desktop import backlight_device
from ..core.state import ConfigError, ROOT, read_object


SAFE_INDICATORS = {
    'brightness': 'brightness',
    'volume': 'volume',
    'microphone': 'microphone',
}
VALID_INDICATORS = tuple(SAFE_INDICATORS.keys())


def indicator(kind):
    safe_kind = SAFE_INDICATORS.get(str(kind))
    if not safe_kind:
        raise ConfigError('Unknown indicator')
    if safe_kind == 'brightness':
        device, value = backlight_device()
        if not device:
            raise ConfigError('No controllable display backlight found')
        return value / 100, False
    node = '@DEFAULT_AUDIO_SINK@' if safe_kind == 'volume' else '@DEFAULT_AUDIO_SOURCE@'
    response = subprocess.run(['wpctl', 'get-volume', node], capture_output=True, text=True, timeout=3)
    match = re.search(r'Volume:\s*([0-9.]+)', response.stdout)
    if response.returncode or not match:
        raise ConfigError('Audio device is unavailable')
    return max(0.0, float(match[1])), '[MUTED]' in response.stdout


def show_indicator(kind):
    safe_kind = SAFE_INDICATORS.get(str(kind))
    if not safe_kind:
        raise ConfigError('Unknown indicator')
    value, muted = indicator(safe_kind)
    subprocess.run(['quickshell', 'ipc', '--path', str(ROOT / 'shell'), 'call', 'shell',
                    'showOsd', safe_kind, str(value), "true" if muted else "false"], check=True, timeout=3)  # NOSONAR


def mako_style(snapshot):
    palette = snapshot.get('appearance', {}).get('palette') or snapshot['profile']['palette']
    font = snapshot.get('appearance', {}).get('fonts', {}).get('interface', 'Inter 11')
    if '\n' in font or '\r' in font:
        raise ConfigError('Invalid notification font')
    from ..theming.visual import validate
    visual = validate(snapshot.get('visual', {}))
    alpha = round(visual['notificationOpacity'] * 255 / 100)
    # profile palette validation has already checked hex colors.
    return f'''# Generated by Poly Shell from the current theme and mode.
font={font}
background-color={palette['background']}{alpha:02x}
text-color={palette['text']}
border-color={palette['accent']}b3
border-size={visual['notificationBorder']}
border-radius={visual['notificationRadius']}
padding={visual['notificationPadding']}
width=360
height=180
outer-margin=10,18,18,18
margin=0,0,10,0
anchor=top-right
layer=overlay
default-timeout=6000
max-visible=3
max-history=100
icons=1
max-icon-size=36
icon-border-radius=8
markup=1
actions=1
format=<b>%s</b>\\n%b
on-button-left=invoke-default-action
on-button-right=dismiss
on-button-middle=dismiss

[urgency=critical]
border-color=#d18e82
default-timeout=0

[mode=do-not-disturb]
invisible=1
'''


def sync_notifications(paths):
    """Write only our generated include; never replace the user's Mako config."""
    text = mako_style(read_object(paths.session))
    paths.state.mkdir(parents=True, exist_ok=True)
    destination = paths.state / 'mako-theme.conf'
    if destination.exists() and destination.read_text() == text:
        return
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', dir=paths.state, delete=False) as stream:
            temporary = stream.name
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, destination)
    finally:
        if temporary and os.path.exists(temporary):
            os.unlink(temporary)
    # Notifications are optional: a missing daemon must not take down the bar.
    try:
        subprocess.run(['makoctl', 'reload'], capture_output=True, timeout=3, check=False)
    except (OSError, subprocess.TimeoutExpired):
        pass
